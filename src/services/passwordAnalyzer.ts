import { ZxcvbnFactory } from '@zxcvbn-ts/core';
import * as zxcvbnCommonPackage from '@zxcvbn-ts/language-common';
import * as zxcvbnEnPackage from '@zxcvbn-ts/language-en';

import {
  PasswordAnalysisResult,
  PasswordStrengthScore,
  PasswordStrengthLabel,
  PatternMatch,
  CrackTimeEstimates,
} from '../types/analyzer';
import { analyzeComposition, calculateEntropy } from './entropyService';
import { checkCommonPassword } from '../constants/commonPasswords';
import { formatSecondsToTime } from '../constants/attackProfiles';

// Instantiate ZxcvbnFactory with English & common dictionaries
let zxcvbnInstance: ZxcvbnFactory | null = null;
try {
  const options = {
    translations: zxcvbnEnPackage.translations,
    graphs: zxcvbnCommonPackage.adjacencyGraphs,
    dictionary: {
      ...zxcvbnCommonPackage.dictionary,
      ...zxcvbnEnPackage.dictionary,
    },
  };
  zxcvbnInstance = new ZxcvbnFactory(options);
} catch (err) {
  console.warn('ZxcvbnFactory initialization warning:', err);
}

const SCORE_LABELS: Record<PasswordStrengthScore, PasswordStrengthLabel> = {
  0: 'Very Weak',
  1: 'Weak',
  2: 'Moderate',
  3: 'Strong',
  4: 'Very Strong',
};

/**
 * Detects custom heuristic patterns including sequential characters, repeats,
 * and predictable substitutions.
 */
function detectAdditionalPatterns(password: string): PatternMatch[] {
  const patterns: PatternMatch[] = [];

  // 1. Repeated characters (3 or more consecutive identical characters)
  const repeatRegex = /(.)\1{2,}/g;
  let match: RegExpExecArray | null;
  while ((match = repeatRegex.exec(password)) !== null) {
    patterns.push({
      type: 'repeat',
      pattern: 'Repeated Characters',
      matchedText: match[0],
      startIndex: match.index,
      endIndex: match.index + match[0].length,
      explanation: `Repeated character '${match[1]}' (${match[0].length} times) drastically reduces entropy.`,
    });
  }

  // 2. Sequential numbers (e.g., 123, 1234, 4321, 7890)
  const numberSequences = [
    '0123456789', '9876543210', '123456', '654321', '12345', '54321', '1234', '4321',
    '2345', '3456', '4567', '5678', '6789', '123', '234', '345', '456', '567', '678', '789',
    '321', '432', '543', '654', '765', '876', '987', '012', '210'
  ];
  const lowerPwd = password.toLowerCase();
  for (const seq of numberSequences) {
    const idx = lowerPwd.indexOf(seq);
    if (idx !== -1) {
      patterns.push({
        type: 'sequence',
        pattern: 'Sequential Numbers',
        matchedText: password.substring(idx, idx + seq.length),
        startIndex: idx,
        endIndex: idx + seq.length,
        explanation: `Sequential number pattern "${seq}" is one of the first patterns tested by cracking tools.`,
      });
      break;
    }
  }

  // 3. Sequential alphabet (e.g., abc, abcd, defg, dcba)
  const alphabetSequences = [
    'abcdef', 'bcdefg', 'cdefgh', 'defghi', 'efghij', 'fedcba', 'edcba', 'abcd', 'bcde', 'cdef',
    'abc', 'bcd', 'cde', 'def', 'efg', 'fgh', 'cba', 'dcb', 'edc', 'fed'
  ];
  for (const seq of alphabetSequences) {
    const idx = lowerPwd.indexOf(seq);
    if (idx !== -1) {
      patterns.push({
        type: 'sequence',
        pattern: 'Sequential Letters',
        matchedText: password.substring(idx, idx + seq.length),
        startIndex: idx,
        endIndex: idx + seq.length,
        explanation: `Alphabetical sequence "${seq}" is easily detected and generated by rule-based engines.`,
      });
      break;
    }
  }

  // 4. Keyboard walks (e.g., qwerty, asdf, zxcv)
  const keyboardWalks = ['qwerty', 'asdfgh', 'zxcvbn', 'qwert', 'asdfg', 'zxcvb', 'werty', 'sdfgh', 'xcvbn'];
  for (const walk of keyboardWalks) {
    const idx = lowerPwd.indexOf(walk);
    if (idx !== -1) {
      patterns.push({
        type: 'spatial',
        pattern: 'Keyboard Walk',
        matchedText: password.substring(idx, idx + walk.length),
        startIndex: idx,
        endIndex: idx + walk.length,
        explanation: `Spatial keyboard walk "${walk}" requires near-zero entropy to guess.`,
      });
      break;
    }
  }

  // 5. Predictable years (1950 - 2035)
  const yearMatch = password.match(/(19[5-9]\d|20[0-3]\d)/);
  if (yearMatch && yearMatch.index !== undefined) {
    patterns.push({
      type: 'date',
      pattern: 'Calendar Year',
      matchedText: yearMatch[0],
      startIndex: yearMatch.index,
      endIndex: yearMatch.index + 4,
      explanation: `Common year reference "${yearMatch[0]}" is prioritized in hybrid brute-force attacks.`,
    });
  }

  // 6. L33t substitutions
  if (/[@$0!31]/.test(password)) {
    const l33tDetected = password.replace(/[@]/g, 'a')
      .replace(/[$]/g, 's')
      .replace(/[0]/g, 'o')
      .replace(/[!]/g, 'i')
      .replace(/[3]/g, 'e')
      .replace(/[1]/g, 'l');
    if (l33tDetected !== password) {
      patterns.push({
        type: 'l33t',
        pattern: 'L33t Speak Substitution',
        matchedText: password,
        startIndex: 0,
        endIndex: password.length,
        explanation: 'Predictable character substitutions (such as @ for a, $ for s, 0 for o) are standard in Hashcat attack rules.',
      });
    }
  }

  return patterns;
}

/**
 * Calculates estimated crack times for four standardized attack scenarios
 */
function calculateCrackTimes(guesses: number): CrackTimeEstimates {
  // Scenario 1: Online strictly throttled (100 guesses / hour = ~0.0277 / sec)
  const secondsOnlineThrottled = guesses / (100 / 3600);

  // Scenario 2: Online unthrottled API (10 guesses / sec)
  const secondsOnlineStandard = guesses / 10;

  // Scenario 3: Offline slow hash (10,000 guesses / sec - bcrypt/Argon2id)
  const secondsOfflineSlow = guesses / 10_000;

  // Scenario 4: Offline fast hash (100,000,000,000 guesses / sec - 8x RTX 4090 MD5/NTLM)
  const secondsOfflineFast = guesses / 100_000_000_000;

  return {
    onlineThrottled: formatSecondsToTime(secondsOnlineThrottled),
    onlineStandard: formatSecondsToTime(secondsOnlineStandard),
    offlineSlowHash: formatSecondsToTime(secondsOfflineSlow),
    offlineFastHash: formatSecondsToTime(secondsOfflineFast),
  };
}

/**
 * Analyzes password in real-time entirely client-side.
 * Never stores or transmits the input.
 */
export function analyzePassword(password: string): PasswordAnalysisResult {
  // Safety check for empty or whitespace
  if (!password || password.length === 0) {
    const emptyComp = analyzeComposition('');
    return {
      password: '',
      score: 0,
      label: 'Very Weak',
      guesses: 0,
      guessesLog10: 0,
      crackTimes: {
        onlineThrottled: 'Instant',
        onlineStandard: 'Instant',
        offlineSlowHash: 'Instant',
        offlineFastHash: 'Instant',
      },
      composition: emptyComp,
      entropy: calculateEntropy('', 0, emptyComp),
      patterns: [],
      suggestions: ['Enter a password to begin real-time strength analysis.'],
      isCommonPassword: false,
      analyzedAt: Date.now(),
    };
  }

  // Check against common breached passwords first
  const commonMatch = checkCommonPassword(password);

  // Run zxcvbn analysis (capped at 72 chars per Dropbox zxcvbn best practices to prevent graph search delays)
  const passwordForZxcvbn = password.length > 72 ? password.substring(0, 72) : password;
  let zxResult;
  try {
    if (zxcvbnInstance) {
      zxResult = zxcvbnInstance.check(passwordForZxcvbn);
    } else {
      throw new Error('ZxcvbnFactory not initialized');
    }
  } catch (err) {
    console.warn('zxcvbn analysis error fallback:', err);
    zxResult = {
      score: 1,
      guesses: Math.pow(10, Math.min(password.length, 12)),
      guessesLog10: Math.min(password.length, 12),
      feedback: {
        warning: 'Analysis completed with basic heuristic model',
        suggestions: ['Use a longer password with mixed character classes.'],
      },
      sequence: [],
    };
  }

  // Derive initial score and guesses
  let score = zxResult.score as PasswordStrengthScore;
  let guesses = zxResult.guesses;
  let guessesLog10 = zxResult.guessesLog10;

  // If matched in top common list, override score to 0 (Very Weak)
  if (commonMatch.isCommon) {
    score = 0;
    guesses = Math.min(guesses, 100);
    guessesLog10 = Math.min(guessesLog10, 2);
  }

  // Composition & Entropy
  const composition = analyzeComposition(password);
  const entropy = calculateEntropy(password, guesses, composition);

  // Detect additional patterns (capped to 256 chars for performance)
  const patternSample = password.length > 256 ? password.substring(0, 256) : password;
  const patterns = detectAdditionalPatterns(patternSample);

  // Add zxcvbn identified sequence items
  if (zxResult.sequence && Array.isArray(zxResult.sequence)) {
    for (const matchItem of zxResult.sequence) {
      if (matchItem.pattern === 'dictionary') {
        patterns.push({
          type: 'dictionary',
          pattern: `Dictionary Word (${matchItem.dictionaryName || 'common'})`,
          matchedText: matchItem.token,
          startIndex: matchItem.i,
          endIndex: matchItem.j + 1,
          explanation: `Identified dictionary word "${matchItem.token}". Words in dictionaries are targeted by wordlist attacks.`,
        });
      } else if (matchItem.pattern === 'spatial') {
        patterns.push({
          type: 'spatial',
          pattern: 'Spatial Keyboard Pattern',
          matchedText: matchItem.token,
          startIndex: matchItem.i,
          endIndex: matchItem.j + 1,
          explanation: `Pattern "${matchItem.token}" follows adjacent keys on standard keyboards.`,
        });
      }
    }
  }

  // Synthesize warning & suggestions
  let warning = commonMatch.warning || zxResult.feedback?.warning || undefined;
  const suggestions: string[] = [];

  if (commonMatch.isCommon) {
    suggestions.push('Never use passwords that appear on public breach blocklists.');
  }

  if (composition.length < 12) {
    suggestions.push(`Password length is only ${composition.length} characters. Aim for at least 14-16 characters.`);
  }

  if (composition.poolSize < 50 && composition.length < 20) {
    suggestions.push('Add uppercase letters, numbers, or symbols to expand the search space.');
  }

  if (patterns.some(p => p.type === 'repeat')) {
    suggestions.push('Eliminate repeated character blocks like "aaa" or "111".');
  }

  if (patterns.some(p => p.type === 'sequence')) {
    suggestions.push('Replace sequential sequences like "1234" or "abcd" with unpredictable random characters.');
  }

  if (zxResult.feedback?.suggestions && Array.isArray(zxResult.feedback.suggestions)) {
    for (const s of zxResult.feedback.suggestions) {
      if (s && !suggestions.includes(s)) {
        suggestions.push(s);
      }
    }
  }

  if (score >= 3 && suggestions.length === 0) {
    suggestions.push('Great job! This password demonstrates strong resistance to automated guessing attacks.');
  }

  const crackTimes = calculateCrackTimes(guesses);

  return {
    password,
    score,
    label: SCORE_LABELS[score],
    guesses,
    guessesLog10: Number(guessesLog10.toFixed(1)),
    crackTimes,
    composition,
    entropy,
    patterns,
    warning,
    suggestions: suggestions.slice(0, 5),
    isCommonPassword: commonMatch.isCommon,
    commonRank: commonMatch.rank,
    analyzedAt: Date.now(),
  };
}
